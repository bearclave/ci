#!/usr/bin/env python3
"""Writes the reusable workflows that carry a script from src/.

A reusable workflow runs in the calling repository, and the caller's token
cannot read this private repository, so a script cannot be checked out next
to the workflow. It travels inside the workflow instead: templates/<name>.yml
has a line `@@include src/<script>@@` inside a heredoc, and this puts the
script there, indented like the marker.

Usage: build.py           write .github/workflows/ from templates/
       build.py --check   fail when .github/workflows/ is not what it would write
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent
MARKER = re.compile(r"^(\s*)@@include (\S+)@@\s*$")
HEADER = "# GENERATED by build.py from templates/{name} - edit the template or src/, not this file.\n"


def render(template: pathlib.Path) -> str:
    out = [HEADER.format(name=template.name)]
    for line in template.read_text(encoding="utf-8").splitlines(keepends=True):
        m = MARKER.match(line)
        if not m:
            out.append(line)
            continue
        indent, path = m.groups()
        source = (ROOT / path).read_text(encoding="utf-8")
        # GitHub reads ${{ anywhere in a workflow as the start of an
        # expression, heredoc or not, and rejects the whole file.
        if "${{" in source:
            sys.exit(f"{path} contains '$' + '{{{{', which a workflow cannot carry")
        for src in source.splitlines():
            out.append((indent + src).rstrip() + "\n" if src.strip() else "\n")
    return "".join(out)


def main(check: bool) -> int:
    stale = []
    for template in sorted((ROOT / "templates").glob("*.yml")):
        target = ROOT / ".github" / "workflows" / template.name
        text = render(template)
        if check:
            if not target.exists() or target.read_text(encoding="utf-8") != text:
                stale.append(str(target.relative_to(ROOT)))
        else:
            target.write_text(text, encoding="utf-8")
    for path in stale:
        print(f"::error file={path}::not what build.py writes from templates/ - run ./build.py")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))
