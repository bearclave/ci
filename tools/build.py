#!/usr/bin/env python3
"""Writes the reusable workflows that carry a script from src/.

A reusable workflow runs in the calling repository, and the caller's token
reaches only that repository, so a script cannot be checked out next
to the workflow. It travels inside the workflow instead: templates/<name>.yml
has a line `@@include src/<script>@@` inside a heredoc, and this puts the
script there, indented like the marker.

`@@include templates/_fragments/<name>.yml@@` puts a piece of workflow (a job
or a group of steps shared by several workflows) in the same way, and the
fragment's own markers are expanded too. Templates whose name starts with `_`
are fragments and produce no workflow of their own.

Usage: tools/build.py           write .github/workflows/ from templates/
       tools/build.py --check   fail when .github/workflows/ is not what it would write
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
MARKER = re.compile(r"^(\s*)@@include (\S+)@@\s*$")
# GitHub reads every file in .github/workflows on a push to this repository
# and fails a run "because of a workflow file issue" for one that is too large,
# although a caller can still use it (#48): 433,330 bytes passed, 554,214 did
# not, so the limit is taken as 512 KiB. A larger workflow is refused here:
# carry fewer scripts per job.
MAX_BYTES = 512 * 1024
HEADER = "# GENERATED by tools/build.py from templates/{name} - edit the template or src/, not this file.\n"


def expand(path: pathlib.Path, seen: tuple = ()) -> list:
    """Lines of a template or fragment with every marker replaced."""
    if path in seen:
        sys.exit(f"{path} includes itself")
    out = []
    for line in path.read_text(encoding="utf-8").splitlines(keepends=True):
        m = MARKER.match(line)
        if not m:
            out.append(line)
            continue
        indent, rel = m.groups()
        target = ROOT / rel
        if target.parent.name == "_fragments":
            # A piece of workflow: its expressions are meant to be there.
            lines = [x.rstrip("\n") for x in expand(target, seen + (path,))]
        else:
            source = target.read_text(encoding="utf-8")
            # GitHub reads ${{ anywhere in a workflow as the start of an
            # expression, heredoc or not, and rejects the whole file.
            if "${{" in source:
                sys.exit(f"{rel} contains '$' + '{{{{', which a workflow cannot carry")
            lines = source.splitlines()
        for src in lines:
            out.append((indent + src).rstrip() + "\n" if src.strip() else "\n")
    return out


def render(template: pathlib.Path) -> str:
    return HEADER.format(name=template.name) + "".join(expand(template))


def main(check: bool) -> int:
    stale, large = [], []
    for template in sorted((ROOT / "templates").glob("[!_]*.yml")):
        target = ROOT / ".github" / "workflows" / template.name
        text = render(template)
        size = len(text.encode("utf-8"))
        if size > MAX_BYTES:
            large.append((str(target.relative_to(ROOT)), size))
            continue
        if check:
            if not target.exists() or target.read_text(encoding="utf-8") != text:
                stale.append(str(target.relative_to(ROOT)))
        else:
            target.write_text(text, encoding="utf-8")
    for path in stale:
        print(f"::error file={path}::not what build.py writes from templates/ - run tools/build.py")
    for path, size in large:
        print(f"::error file={path}::{size} bytes, over the {MAX_BYTES} GitHub accepts in .github/workflows (#48) - include fewer scripts per job")
    return 1 if stale or large else 0


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))
