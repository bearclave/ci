#!/usr/bin/env python3
"""Writes the copies of the shared workflows that the template repositories carry.

The templates are copied to customers, whose organisations cannot reach this
private repository, so a template calls a local copy instead
(`uses: ./.github/workflows/security.yml`). The copy is the workflow from here
with what belongs to this organisation taken out:

- the header says it is a local reusable workflow, not bearclave/ci@v1;
- security.yml runs zizmor with its default policy: the ref-pin allowance for
  bearclave/* and the switch-off of ref-confusion exist only because this
  repository is private.

Usage: export-for-templates.py <template checkout> [<template checkout> ...]
       export-for-templates.py --check <template checkout> ...

Which workflows a template gets is read from it: every workflow file of this
repository that the template already has is rewritten. --check writes nothing
and fails when a copy is not what this would write.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SHARED = ("security.yml", "conventions.yml", "sentinel-lint.yml")


def header_end(text: str) -> int:
    """Index of `name:`, where the header comment ends."""
    m = re.search(r"^name: ", text, re.M)
    return m.start()


def security(text: str) -> str:
    head = """# Security checks on every pull request: no secret anywhere in the history,
# workflows that are sound and shell scripts without real defects. The other
# workflows of this repository call it as a local reusable workflow, so the
# check reports as "security / scan":
#
#   jobs:
#     security:
#       uses: ./.github/workflows/security.yml
#       permissions:
#         contents: read
#
# The tools arrive as release binaries checked against the sha256 below, so
# that nothing beyond GitHub-owned actions is needed. Dependabot does not see
# these pins; a version and its checksum are bumped together, by hand. The
# checksum is the `digest` GitHub publishes with the release asset.
"""
    body = text[header_end(text):]
    start = body.index("      # The organisation's own reusable workflows are referenced by a moving")
    end = body.index("      # Warnings and errors only")
    body = body[:start] + """      # Online audits (impostor commits, known-vulnerable actions) need the
      # token.
      - name: zizmor
        env:
          GH_TOKEN: ${{ github.token }}
        run: zizmor --persona=regular --min-severity=medium .github/workflows

""" + body[end:]
    body = body.replace("""      # Stands in for secret scanning, which a private repository gets only
      # with the paid Secret Protection add-on. A false positive is allowed in
      # the repository's .gitleaks.toml, with the reason written next to it.""",
                        """      # Stands in for secret scanning where the repository does not have it.
      # A false positive is allowed in the repository's .gitleaks.toml, with
      # the reason written next to it.""")
    return head + body


def embedded(text: str) -> str:
    """conventions.yml and sentinel-lint.yml: local caller, no word of bearclave/ci."""
    text = re.sub(r"^# GENERATED by (?:tools/)?build\.py[^\n]*\n", "", text)
    text = re.sub(r"uses: bearclave/ci/\.github/workflows/([\w-]+\.yml)@v1", r"uses: ./.github/workflows/\1", text)
    text = text.replace(" The\n# rules themselves are in src/conventions.py of bearclave/ci.", "")
    text = text.replace("; the checks are in src/sentinel_lint.py of bearclave/ci.", ".")
    text = text.replace("""      # The script travels inside this workflow (see build.py): the caller's
      # token cannot read bearclave/ci.""", """      # The script travels inside this workflow, so the workflow file is all a
      # repository needs.""")
    return text


def export(name: str) -> str:
    text = (ROOT / ".github" / "workflows" / name).read_text(encoding="utf-8")
    out = security(text) if name == "security.yml" else embedded(text)
    if "bearclave" in out.lower():
        bad = [line for line in out.splitlines() if "bearclave" in line.lower()]
        sys.exit(f"{name}: the template copy still names the organisation: {bad[:3]}")
    return out


def main(args) -> int:
    check = "--check" in args
    stale = []
    for target in [pathlib.Path(a) for a in args if not a.startswith("--")]:
        workflows = target / ".github" / "workflows"
        for name in SHARED:
            path = workflows / name
            if not path.exists():
                continue
            text = export(name)
            if check:
                if path.read_text(encoding="utf-8") != text:
                    stale.append(str(path))
            else:
                path.write_text(text, encoding="utf-8")
                print(f"wrote {path}")
    for path in stale:
        print(f"stale: {path} - run tools/export-for-templates.py on it")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
